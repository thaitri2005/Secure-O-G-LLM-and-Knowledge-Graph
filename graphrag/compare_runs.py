"""Side-by-side table of answer runs on one question set, for reading by people.

    python -m graphrag.compare_runs --gold graphrag/gold/ak3_events_v0.json \
        --run "Event graph=graphrag/results/E28_graph.json" \
        --run "Plain RAG=graphrag/results/E28_plain_all.json" \
        --out docs/experiments/E28-answers/frozen35

Writes <out>.csv and <out>.md. Reads only recorded runs; no model call.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


def _load(path: str) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _fmt_values(row: dict | None) -> str:
    if row is None:
        return "(not run)"
    if row.get("status") != "answered" or not row.get("values"):
        return f"({row.get('status', 'no answer')})"
    units = row.get("units") or []
    out = []
    for i, v in enumerate(row["values"]):
        u = units[i] if i < len(units) and units[i] else ""
        out.append(f"{v} {u}".strip())
    return "; ".join(out)


def _mark(row: dict | None) -> str:
    if row is None:
        return ""
    if row.get("correct"):
        return "correct"
    if row.get("status") != "answered" or not row.get("values"):
        return "abstained"
    return "wrong" if not row.get("no_wrong_values", True) else "incomplete"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--gold", required=True)
    ap.add_argument("--run", action="append", required=True, help="Label=path to a result JSON")
    ap.add_argument("--out", required=True, help="Output path without extension")
    args = ap.parse_args()

    gold = _load(args.gold)
    facts = {f["id"]: f for f in gold["facts"]}
    runs = []
    for spec in args.run:
        label, path = spec.split("=", 1)
        data = _load(path)
        runs.append((label, Path(path).name, data, {r["id"]: r for r in data["rows"]}))

    header = ["id", "kind", "question", "gold answer"]
    for label, *_ in runs:
        header += [f"{label}: answer", f"{label}: result"]
    table = []
    for q in gold["questions"]:
        gold_txt = "; ".join(
            f"{facts[f]['value']} {facts[f].get('unit', '')}".strip() for f in q["gold"] if f in facts
        )
        line = [q["id"], q.get("kind", ""), q["question"], gold_txt]
        for _, _, _, rows in runs:
            row = rows.get(q["id"])
            line += [_fmt_values(row), _mark(row)]
        table.append(line)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.with_suffix(".csv").open("w", encoding="utf-8-sig", newline="") as fh:
        csv.writer(fh).writerows([header, *table])

    n = len(gold["questions"])
    md = [f"# {out.name}: {n} questions, side by side", ""]
    md.append(f"Questions: `{Path(args.gold).name}` (simulated, not reviewed by an expert). "
              "Gold is computed by code from the PDFs' text layer. Generated by `graphrag/compare_runs.py`.")
    md += ["", "| Method | Result file | Correct | LLM calls | Prompt tokens | Seconds |", "|---|---|---:|---:|---:|---:|"]
    for label, fname, data, rows in runs:
        cost = data.get("cost", {})
        correct = sum(1 for r in rows.values() if r.get("correct"))
        md.append(f"| {label} | `{fname}` | {correct}/{n} | {cost.get('calls', '')} | "
                  f"{cost.get('prompt_tokens', '')} | {cost.get('seconds', '')} |")
    md += ["", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for line in table:
        md.append("| " + " | ".join(str(c).replace("|", "/") for c in line) + " |")
    out.with_suffix(".md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}.csv and {out}.md")


if __name__ == "__main__":
    main()
