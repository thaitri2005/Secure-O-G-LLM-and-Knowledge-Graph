class ExactResolveTest(unittest.TestCase):
    def test_near_threshold_resolution_is_repeatable(self):
        load_env()
        tmp = clean_dir(PROJECT_ROOT / ".cache/tmp/tests/resolve_exact")
        saved = socket.socket.connect, socket.socket.connect_ex, socket.getaddrinfo
        guard_network(tmp / "net.jsonl")
        try:
            cfg = load_config(PROJECT_ROOT / "configs/experiments/showcase.yaml")
            self.assertEqual(cfg.resolve.semhash_threshold, 0.95)
            expected = None
            for iteration in range(50):
                with self.subTest(iteration=iteration):
                    result = resolve(list(SURFACES), [], [], cfg, True)
                    self.assertEqual(result.by_key["cnut"], result.by_key["cnut the great"])
                    if expected is None:
                        expected = result
                    else:
                        self.assertEqual(result, expected)
        finally:
            socket.socket.connect, socket.socket.connect_ex, socket.getaddrinfo = saved
        self.assertEqual(blocked_count(tmp / "net.jsonl"), 0)


if __name__ == "__main__":
    unittest.main()
